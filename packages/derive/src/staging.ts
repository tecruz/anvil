/**
 * The staging and apply lifecycle.
 *
 * `init` never writes into a checked-out repository. It writes a staging bundle under
 * `.anvil/staging/`, renders a diff, and stops. `--apply` is the only operation that
 * mutates the repo, and it re-checks that the bundle still matches the repository it was
 * derived from.
 *
 * Why the staleness check is the important part: the user is very likely to edit the
 * staged files (that is the point -- the agent improves them), run `init --apply` some
 * time later, and by then the repository may have changed underneath. Applying a bundle
 * derived from a different repository state would silently overwrite work. So the bundle
 * records a hash of its inputs, and `--apply` refuses when the current inputs no longer
 * hash the same.
 *
 * The bundle is content-addressed by that input hash, so re-running `init` on an unchanged
 * repository regenerates an identical bundle. That is what makes the idempotence test
 * well-defined.
 */

import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { AnvilError, ErrorCode } from '@anvil/core'

export const STATE_DIR = '.anvil'
export const STAGING_DIR = join(STATE_DIR, 'staging')
export const MANIFEST_NAME = 'manifest.json'
export const FILES_SUBDIR = 'files'

export interface StagedFile {
  /** Repo-relative POSIX path the file will be written to. */
  path: string
  /** Path within the staging bundle. */
  stagedPath: string
  sha256: string
  bytes: number
  /**
   * Hash of the repository's copy of this file at the moment it was staged, or null if
   * the file did not exist then.
   *
   * This is what makes the staleness check meaningful. Comparing the repository against
   * the *staged* content cannot tell "the repo changed since staging" apart from "the repo
   * always differed from what anvil generates", and conflating them refuses `--apply`
   * forever on any repo that already has an AGENTS.md -- with a message claiming the file
   * changed when it never did. Recording the repo side at staging time is what lets apply
   * distinguish: repo-unchanged-since-staging may proceed (the user reviewed the diff);
   * repo-changed-since-staging is refused.
   */
  repoSha256: string | null
}

export interface StagingManifest {
  schemaVersion: 1
  /** Hash of the inputs the bundle was derived from. */
  inputHash: string
  createdAt: string
  files: StagedFile[]
  /** Free-form record of what produced this bundle. */
  generator: string
}

export function sha256(text: string): string {
  return createHash('sha256').update(text, 'utf8').digest('hex')
}

/**
 * Hash the inputs that determine generated output.
 *
 * Only the *inputs* are hashed, not the outputs: the profile, the readiness report, and
 * the matched playbook ids. Two things that cannot change the generated bytes are
 * deliberately excluded, so editing a README does not invalidate a bundle.
 */
export function hashInputs(input: {
  profile: unknown
  report: {
    score: number
    findings: Array<{ id: string; status: string; severity: string }>
  }
  playbookIds: readonly string[]
}): string {
  const canonical = JSON.stringify({
    commands: input.profile,
    findings: input.report.findings.map((f) => [f.id, f.status, f.severity]),
    score: input.report.score,
    playbooks: [...input.playbookIds].sort(),
  })
  return sha256(canonical)
}

export function stagingRoot(repoRoot: string): string {
  return join(repoRoot, '.anvil', 'staging')
}

export function manifestPath(repoRoot: string): string {
  return join(stagingRoot(repoRoot), MANIFEST_NAME)
}

/** Write a staging bundle, replacing any previous one. `files` is derived from `contents`. */
export function writeStaging(
  repoRoot: string,
  manifest: Pick<StagingManifest, 'inputHash' | 'generator'>,
  contents: ReadonlyMap<string, string>,
): StagingManifest {
  const root = stagingRoot(repoRoot)
  rmSync(root, { recursive: true, force: true })
  mkdirSync(join(root, FILES_SUBDIR), { recursive: true })

  const files: StagedFile[] = []
  for (const path of [...contents.keys()].sort()) {
    const content = contents.get(path) as string
    const stagedRel = join(FILES_SUBDIR, path)
    const stagedAbs = join(root, stagedRel)
    mkdirSync(join(stagedAbs, '..'), { recursive: true })
    writeFileSync(stagedAbs, content, 'utf8')
    // Capture the repository's current content for this path, so `--apply` can tell a
    // file that changed after staging from one that merely always differed.
    const existing = readRepoFile(repoRoot, path)
    files.push({
      path,
      stagedPath: stagedRel.split('\\').join('/'),
      sha256: sha256(content),
      bytes: Buffer.byteLength(content),
      repoSha256: existing === null ? null : sha256(existing),
    })
  }

  const full: StagingManifest = {
    schemaVersion: 1,
    createdAt: new Date().toISOString(),
    inputHash: manifest.inputHash,
    generator: manifest.generator,
    files,
  }
  writeFileSync(join(root, MANIFEST_NAME), `${JSON.stringify(full, null, 2)}\n`, 'utf8')
  return full
}

export function readManifest(repoRoot: string): StagingManifest | null {
  const path = manifestPath(repoRoot)
  if (!existsSync(path)) return null
  try {
    const parsed: unknown = JSON.parse(readFileSync(path, 'utf8'))
    if (typeof parsed !== 'object' || parsed === null) return null
    const manifest = parsed as StagingManifest
    if (!Array.isArray(manifest.files)) return null
    // A manifest is a file inside the repository, and `anvil` is explicitly run in
    // repositories it does not own. A committed `.anvil/staging/manifest.json` whose
    // `path` entries are `../../.ssh/authorized_keys` or an absolute path would make
    // `--apply` write attacker-chosen content outside the repository -- `mkdirSync` of the
    // parent included. So every target is checked to be a plain relative path inside the
    // repo before it is ever read or written. (The local ticket provider guards the same
    // class of input for the same reason.)
    for (const file of manifest.files) {
      if (typeof file?.path !== 'string' || typeof file?.stagedPath !== 'string') return null
      if (!isSafeRepoRelativePath(file.path) || !isSafeRepoRelativePath(file.stagedPath)) return null
    }
    return manifest
  } catch {
    return null
  }
}

/**
 * True when a manifest path is a plain relative path with no traversal.
 *
 * Rejects absolute paths, drive letters, `..` segments and backslashes, on every
 * platform, not just Windows: a manifest is data, and the value of a data file is
 * exactly what a hostile repository can control.
 */
function isSafeRepoRelativePath(p: string): boolean {
  if (p === '' || p.startsWith('/') || p.startsWith('\\') || /^[A-Za-z]:/.test(p)) return false
  if (p.includes('\\') || p.includes('\0')) return false
  return !p.split('/').some((seg) => seg === '..' || seg === '')
}

/** Read the staged content for a manifest entry. */
export function readStaged(repoRoot: string, file: StagedFile): string | null {
  const path = join(stagingRoot(repoRoot), file.stagedPath)
  if (!existsSync(path)) return null
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}

/** Read a repo-relative file, or null when absent. */
export function readRepoFile(repoRoot: string, relPath: string): string | null {
  const path = join(repoRoot, relPath)
  if (!existsSync(path)) return null
  try {
    if (!statSync(path).isFile()) return null
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}

export interface StagingState {
  exists: boolean
  manifest: StagingManifest | null
  /** Entries whose staged content no longer matches its recorded hash. */
  tampered: string[]
}

export function inspectStaging(repoRoot: string): StagingState {
  const manifest = readManifest(repoRoot)
  if (manifest === null) return { exists: false, manifest: null, tampered: [] }

  const tampered: string[] = []
  for (const file of manifest.files) {
    const content = readStaged(repoRoot, file)
    // A tampered file is not an error: editing the staged files is the intended workflow.
    // But it must be reported, because it means the bundle differs from what `init`
    // produced, and the user should know the diff they are reviewing includes their edits.
    if (content === null || sha256(content) !== file.sha256) tampered.push(file.path)
  }
  return { exists: true, manifest, tampered }
}

export interface ApplyPrecondition {
  ok: boolean
  reason?: string
  hint?: string
}

/**
 * Decide whether a staged bundle may be applied.
 *
 * Two independent checks, because they catch different mistakes:
 *  - the bundle must still correspond to the repository as it is now (`inputHash`)
 *  - the files it will write must not have changed since staging was produced
 */
export function checkApplyPreconditions(
  repoRoot: string,
  manifest: StagingManifest | null,
  currentInputHash: string,
): ApplyPrecondition {
  if (manifest === null) {
    return {
      ok: false,
      reason: 'No staging bundle found',
      hint: 'Run `anvil init` first to produce one, then `anvil init --apply`.',
    }
  }

  if (manifest.inputHash !== currentInputHash) {
    return {
      ok: false,
      reason: `The staging bundle is stale: it was built from inputs hashing to ${manifest.inputHash.slice(0, 12)} but the repository now hashes to ${currentInputHash.slice(0, 12)}`,
      hint: 'The repository changed since `anvil init` ran. Re-run `anvil init` to rebuild the bundle against the current state.',
    }
  }

  // Second check: the repository must not have changed under the bundle. This is
  // compared against the repo-side hash recorded at staging time, so "the file was edited
  // after init ran" is refused, while a file that already existed (and that the user
  // reviewed as a diff) is allowed to be replaced. Refusing on "content differs from
  // generated" would make every pre-existing AGENTS.md permanently un-applyable.
  for (const file of manifest.files) {
    // A bundle produced before repoSha256 existed cannot make this distinction; treat
    // the repo side as unknown and refuse when it differs, which is the old (safe)
    // behaviour. The cast is because the field is absent from old manifests, not because
    // the field is optional in the current type.
    const repoSha256 = (file as { repoSha256?: string | null }).repoSha256
    const onDisk = readRepoFile(repoRoot, file.path)
    // Content identical to what would be written makes the apply a no-op, so it is always
    // safe -- this is what makes a second `--apply` after a first one a no-op rather than
    // a refusal, even though the file now exists and did not at staging time.
    if (onDisk !== null && sha256(onDisk) === file.sha256) continue
    if (repoSha256 === undefined) {
      if (onDisk !== null) {
        return {
          ok: false,
          reason: `${file.path} differs from the bundle and the bundle predates repo-side tracking`,
          hint: 'Re-run `anvil init` to rebuild the bundle against the current state.',
        }
      }
      continue
    }
    const current = onDisk === null ? null : sha256(onDisk)
    if (current === repoSha256) continue // repo unchanged since staging
    return {
      ok: false,
      reason: `${file.path} changed in the repository since the bundle was staged`,
      hint: 'Inspect the diff above. Re-run `anvil init` to rebuild the bundle against the current state.',
    }
  }

  return { ok: true }
}

/** Write the bundle into the repository. Only called after preconditions pass. */
export function applyStaging(repoRoot: string, manifest: StagingManifest): string[] {
  const written: string[] = []
  for (const file of manifest.files) {
    const content = readStaged(repoRoot, file)
    if (content === null) {
      throw new AnvilError(ErrorCode.Internal, `Staged file disappeared: ${file.path}`, {
        hint: 'Re-run `anvil init` to rebuild the staging bundle.',
      })
    }
    const target = join(repoRoot, file.path)
    mkdirSync(join(target, '..'), { recursive: true })
    writeFileSync(target, content, 'utf8')
    written.push(file.path)
  }
  return written
}

/** Remove the staging bundle. */
export function clearStaging(repoRoot: string): void {
  rmSync(stagingRoot(repoRoot), { recursive: true, force: true })
}

/** Entries anvil writes that must never be committed. */
export const GITIGNORE_SNIPPET = `# anvil's own per-repo state. Staging is regenerated by \`anvil init\`;
# ticket context is company-internal. Never commit either.
.anvil/
`

export function stagingIsEmpty(root: string): boolean {
  const dir = join(root, '.anvil', 'staging')
  if (!existsSync(dir)) return true
  return readdirSync(dir).length === 0
}
