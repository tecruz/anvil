/**
 * Rendering discovery results as playbook YAML for a human to merge.
 *
 * This is the only thing discovery ever produces that resembles curated data, and it is
 * printed rather than written. That asymmetry is deliberate: the failure mode of a tool that
 * edits `registry/playbooks/*.yaml` is that a bad fetch becomes reviewed-looking content,
 * whereas the failure mode of one that prints is that nobody pastes it in. Both are cheap;
 * only one loses the provenance.
 *
 * So the output carries what a hand-merge would otherwise have to reconstruct by hand: which
 * source produced each entry, when, and the evidence that put it in its tier. A maintainer
 * deciding whether to promote `android/skills` to `official.agents` can see that it came
 * from an org-seeded search rather than having to re-run the query and hope.
 *
 * Entries whose URL the playbook already cites are omitted. A patch that re-adds a line
 * already in the file is how a maintainer learns to distrust the output.
 */

import { normalizeUrl, type Playbook } from '@anvil/playbooks'
import type { DiscoveryEntry } from './github.ts'

export interface ProposalBlock {
  playbookId: string
  /** The full YAML document a maintainer would merge into the playbook file. */
  yaml: string
  entries: DiscoveryEntry[]
  /** How many were skipped because the playbook already cites them. */
  duplicates: number
}

const SECTION_FOR_ENTRY: Record<DiscoveryEntry['section'], string> = {
  docs: 'docs',
  skills: 'skills',
  agents: 'agents',
  mcp: 'mcp',
  styleGuides: 'styleGuides',
  migrationGuides: 'migrationGuides',
  community: 'community',
}

/** URLs a playbook already cites, normalised for comparison. */
export function citedUrls(playbook: Pick<Playbook, 'official' | 'community'>): Set<string> {
  const all = [
    ...playbook.official.docs,
    ...playbook.official.skills,
    ...playbook.official.agents,
    ...playbook.official.mcp,
    ...playbook.official.styleGuides,
    ...playbook.official.migrationGuides,
    ...playbook.community,
  ]
  return new Set(all.map((r) => normalizeUrl(r.url)))
}

/**
 * Entries worth promoting: official ones first, then by stars.
 *
 * Official before stars because a repo published by the technology's own org is a stronger
 * claim than a popular third-party one, which is the same ordering the plan tiers use. The
 * sort is total, so the same input always renders the same patch.
 */
export function rankForProposal(entries: readonly DiscoveryEntry[]): DiscoveryEntry[] {
  return [...entries].sort((a, b) => {
    if (a.tier !== b.tier) return a.tier === 'official' ? -1 : 1
    const stars = (b.stars ?? 0) - (a.stars ?? 0)
    if (stars !== 0) return stars
    return a.label.localeCompare(b.label)
  })
}

/** Single-quote a scalar for the playbook YAML subset. */
function quote(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

/**
 * Prose folded across lines, the shape the rest of the registry uses for `why`.
 *
 * Folded rather than quoted because a `why` is a sentence and the registry reads as
 * sentences; a single 200-character quoted line is unreadable in review, which is where a
 * bad entry gets caught or does not.
 */
function blockScalar(text: string, indent: string): string {
  const wrapped = wrap(text, 96)
  return `${indent}why: >-\n${wrapped.map((l) => `${indent}  ${l}`).join('\n')}`
}

function wrap(text: string, width: number): string[] {
  const words = text.replace(/\s+/g, ' ').trim().split(' ')
  const out: string[] = []
  let line = ''
  for (const word of words) {
    if (line === '') {
      line = word
      continue
    }
    if (`${line} ${word}`.length > width) {
      out.push(line)
      line = word
      continue
    }
    line = `${line} ${word}`
  }
  if (line !== '') out.push(line)
  return out.length === 0 ? [''] : out
}

/**
 * Build a proposal for one playbook.
 *
 * Entries with no usable URL are dropped rather than rendered with an empty one: a playbook
 * entry without a URL is a dead link at best, and `check` rejects it as an error, so
 * emitting one would hand the maintainer a patch that fails their own gate.
 */
export function proposePlaybookYaml(
  playbook: Pick<Playbook, 'id' | 'title' | 'official' | 'community'>,
  entries: readonly DiscoveryEntry[],
): ProposalBlock {
  const cited = citedUrls(playbook)
  const usable = rankForProposal(entries).filter((e) => e.url !== '' && !cited.has(normalizeUrl(e.url)))
  const duplicates = entries.length - usable.length

  const lines: string[] = []
  lines.push(`# Proposal for ${playbook.title} (${playbook.id})`)
  lines.push('#')
  lines.push('# Generated by `anvil playbook discover --propose`. Not installed by the tool:')
  lines.push(`# merge what you agree with into registry/playbooks/${playbook.id}.yaml.`)
  lines.push('#')
  lines.push(`# ${String(usable.length)} new entry/entries, ${String(duplicates)} already cited.`)
  if (usable.length === 0) {
    lines.push('#')
    lines.push('# Nothing to add. Every discovered entry is already cited by this playbook.')
    return { playbookId: playbook.id, yaml: `${lines.join('\n')}\n`, entries: [], duplicates }
  }
  lines.push('')

  const bySection = new Map<string, DiscoveryEntry[]>()
  for (const entry of usable) {
    const section = SECTION_FOR_ENTRY[entry.section]
    const list = bySection.get(section)
    if (list === undefined) bySection.set(section, [entry])
    else list.push(entry)
  }

  // Sections in registry order rather than discovery order, so the result is diffable
  // against the file a maintainer has open. The section key is emitted once and every entry
  // hangs off it: repeating it per entry is a duplicate key, and this project's YAML parser
  // rejects duplicates rather than letting the last one win -- which would mean a proposal
  // that silently rendered as one entry out of eight.
  const order = ['docs', 'skills', 'agents', 'mcp', 'styleGuides', 'migrationGuides', 'community']
  const officialSections = order.filter((s) => s !== 'community' && bySection.has(s))

  if (officialSections.length > 0) {
    lines.push('official:')
    for (const section of officialSections) {
      lines.push(`  ${section}:`)
      for (const entry of bySection.get(section) ?? []) {
        lines.push(renderEntry(entry, '    '))
      }
    }
    lines.push('')
  }

  const community = bySection.get('community')
  if (community !== undefined) {
    lines.push('community:')
    for (const entry of community) {
      // A community entry is a bare list item, not a mapping under a key, so its repo is
      // written out rather than derived from the label.
      lines.push(renderEntry(entry, '  ', true))
    }
  }

  return { playbookId: playbook.id, yaml: `${lines.join('\n')}\n`, entries: usable, duplicates }
}

/** One entry, with the discovery evidence as comments above it. */
function renderEntry(entry: DiscoveryEntry, indent: string, community = false): string {
  const out: string[] = []
  out.push(`${indent}# ${entry.source}, fetched ${entry.fetchedAt}, tier ${entry.tier}`)
  if (entry.owner !== null) out.push(`${indent}# owner: ${entry.owner}`)
  if (entry.stars !== null) out.push(`${indent}# stars: ${String(entry.stars)}`)
  out.push(`${indent}- label: ${quote(entry.label)}`)
  out.push(`${indent}  url: ${quote(entry.url)}`)
  out.push(blockScalar(entry.why, `${indent}  `))
  if (community && entry.repo !== null) out.push(`${indent}  repo: ${quote(entry.repo)}`)
  if (entry.install !== null) out.push(`${indent}  install: ${quote(entry.install)}`)
  return out.join('\n')
}
